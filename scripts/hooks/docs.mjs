import { Application } from 'typedoc';
import { mkdtemp, readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const output = join(root, 'docs/hooks');
const temporary = await mkdtemp(join(tmpdir(), 'kingmaker-hook-docs-'));
async function files(dir) {
  const result = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    result.push(...entry.isDirectory() ? await files(path) : [path]);
  }
  return result.sort();
}
try {
  const app = await Application.bootstrapWithPlugins({
    entryPoints: [join(root, 'packages/hooks/src/services.ts')],
    tsconfig: join(root, 'scripts/hooks/tsconfig.json'),
    plugin: ['typedoc-plugin-markdown'],
    readme: join(root, 'scripts/hooks/README.md'),
    name: 'Hook services', disableSources: true, out: temporary,
    entryFileName: 'index', hideBreadcrumbs: true,
  });
  const project = await app.convert();
  if (!project) throw new Error('Hook API conversion failed');
  await app.generateOutputs(project);
  for (const path of await files(temporary)) {
    const body = await readFile(path, 'utf8');
    const title = /^# (.+)$/m.exec(body)?.[1] ?? 'Hook API';
    await writeFile(path, `---\nvisibility: gm\nsummary: ${JSON.stringify(title + ' API reference for conversation hooks.')}\n---\n<!-- Generated by scripts/hooks/docs.mjs. Do not edit. -->\n${body}`);
  }
  if (process.argv.includes('--check')) {
    const generated = await files(temporary);
    const committed = await files(output);
    const names = generated.map(path => relative(temporary, path));
    if (JSON.stringify(names) !== JSON.stringify(committed.map(path => relative(output, path)))) throw new Error('Hook reference file set differs');
    for (const name of names) if (await readFile(join(temporary, name), 'utf8') !== await readFile(join(output, name), 'utf8')) throw new Error(`Hook reference differs: ${name}`);
  } else {
    await rm(output, { recursive: true, force: true });
    for (const path of await files(temporary)) {
      const target = resolve(output, relative(temporary, path));
      await mkdir(join(target, '..'), { recursive: true });
      await writeFile(target, await readFile(path));
    }
  }
} catch (error) {
  throw new Error(`${error.message}. Run proto run moon -- run workspace:hooksDocsGenerate`, { cause: error });
} finally { await rm(temporary, { recursive: true, force: true }); }
